/** Shared, dependency-free local release bookkeeping. No network or deployment. */
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const WEBSITE = fileURLToPath(new URL('../', import.meta.url));
export const STUDY = path.resolve(WEBSITE, '..');
export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
export const readJson = async (relative) => JSON.parse(await fs.readFile(path.join(WEBSITE, relative), 'utf8'));
export const writeJson = async (relative, value) => {
  const target = path.join(WEBSITE, relative);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, `${JSON.stringify(value, null, 2)}\n`);
};
export async function filesBelow(directory, prefix = '') {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const out = [];
  for (const entry of entries) {
    if (entry.isSymbolicLink()) throw new Error(`Release input cannot be a symbolic link: ${prefix}/${entry.name}`);
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...await filesBelow(path.join(directory, entry.name), relative));
    else if (entry.isFile()) out.push(relative);
  }
  return out.sort();
}
export async function describeFile(directory, relative) {
  const bytes = await fs.readFile(path.join(directory, relative));
  return { path: relative, bytes: bytes.length, sha256: sha256(bytes) };
}
export async function sourceInputs() {
  const candidates = ['package.json', 'package-lock.json', 'index.html', 'vite.config.ts', 'tsconfig.json'];
  for (const directory of ['src', 'scripts']) {
    candidates.push(...(await filesBelow(path.join(WEBSITE, directory))).filter((file) => !file.includes('__pycache__/') && !file.endsWith('.pyc')).map((file) => `${directory}/${file}`));
  }
  try { candidates.push(...(await filesBelow(path.join(WEBSITE, 'public/ui'))).map((file) => `public/ui/${file}`)); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  const unique = [...new Set(candidates)].filter((file) => file !== 'src/generated/uiRelease.ts').sort();
  const files = await Promise.all(unique.map((file) => describeFile(WEBSITE, file)));
  return { files, fingerprint: sha256(Buffer.from(JSON.stringify(files))) };
}
export function mimeType(relative) {
  const extension = path.extname(relative).toLowerCase();
  return ({ '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.png': 'image/png', '.webp': 'image/webp', '.svg': 'image/svg+xml', '.txt': 'text/plain; charset=utf-8', '.csv': 'text/csv; charset=utf-8', '.ico': 'image/x-icon', '.htaccess': 'text/plain; charset=utf-8' })[extension] ?? (path.basename(relative) === '.htaccess' ? 'text/plain; charset=utf-8' : 'application/octet-stream');
}
export async function expectedIdentity() {
  const manifestBytes = await fs.readFile(path.join(WEBSITE, 'public/research/manifest.json'));
  const manifest = JSON.parse(manifestBytes);
  const inputs = await sourceInputs();
  const identity = {
    schemaVersion: 1, uiBuildId: `ui-w6-${inputs.fingerprint.slice(0, 20)}`,
    dataReleaseId: manifest.dataReleaseId, exportManifestVersion: manifest.schemaVersion,
    exportManifestSha256: sha256(manifestBytes), studyId: manifest.studyId,
    studyFrozenAt: manifest.studyFrozenAt, sourceInventorySha256: manifest.sourceInventorySha256,
    sourceFingerprint: inputs.fingerprint,
  };
  return { identity, inputs };
}
export function identityModule(identity) {
  return `// Generated by scripts/prepare-ui-release.mjs immediately before the build.\n// The UI fingerprint excludes this module to avoid a self-reference.\nexport const UI_RELEASE = ${JSON.stringify(identity, null, 2)} as const;\nexport const UI_RELEASE_ID = UI_RELEASE.uiBuildId;\nexport const EXPORT_MANIFEST_VERSION = UI_RELEASE.exportManifestVersion;\n`;
}
export async function assertPrepared() {
  const expected = await expectedIdentity();
  const actual = await fs.readFile(path.join(WEBSITE, 'src/generated/uiRelease.ts'), 'utf8');
  if (actual !== identityModule(expected.identity)) throw new Error('UI identity is stale. Run prepare-ui-release.mjs and rebuild before packaging.');
  return expected;
}

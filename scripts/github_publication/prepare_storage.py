"""Prepare complete, disjoint publication dispositions and byte-verified local archives.
Uses the immutable Phase 1 backup for unchanged inputs, never alters historical
project evidence, initializes no Git repository, and performs no upload.
"""
from __future__ import annotations
import argparse, collections, datetime as dt, fnmatch, gzip, hashlib, json, os, re, shutil, stat, zipfile
from pathlib import Path, PurePosixPath
VERSION="1.0.0"
CHUNK=4*1024*1024

def emit(v): print(json.dumps(v,ensure_ascii=True),flush=True)
def sha(p):
    h=hashlib.sha256()
    with open(p,"rb") as f:
        for b in iter(lambda:f.read(CHUNK),b""): h.update(b)
    return h.hexdigest()
def read(p): return json.loads(Path(p).read_text(encoding="utf-8-sig"))
def encoded(v): return (json.dumps(v,indent=2,ensure_ascii=False)+"\n").encode("utf-8")
def new(p,data):
    p=Path(p); p.parent.mkdir(parents=True,exist_ok=True)
    with open(p,"xb") as f: f.write(data)
def json_new(p,v): new(p,encoded(v))
def safe_name(p):
    if not p or "\\" in p or ":" in p or p.startswith("/") or any(x in ("",".","..") for x in p.split("/")):
        raise RuntimeError("Unsafe relative path: "+repr(p))
    return p
def join(root,p): return Path(root).joinpath(*safe_name(p).split("/"))
def is_control(p,policy):
    return any(p==x or (x.endswith("/") and p.startswith(x)) for x in policy["phase2_control_paths"])
def fast_scan(root,policy):
    result={}; directories=set()
    def visit(folder,relative=""):
        directories.add(relative)
        with os.scandir(folder) as stream: entries=list(stream)
        for e in entries:
            rel=(relative+"/" if relative else "")+e.name
            if is_control(rel,policy): continue
            s=e.stat(follow_symlinks=False)
            if e.is_symlink() or getattr(s,"st_file_attributes",0)&0x400:
                raise RuntimeError("Unhandled reparse point: "+rel)
            if e.is_dir(follow_symlinks=False): visit(e.path,rel)
            elif e.is_file(follow_symlinks=False):
                result[rel]={"bytes":s.st_size,"mtime_ns":s.st_mtime_ns,
                "attributes":getattr(s,"st_file_attributes",0),"mode":s.st_mode}
            else: raise RuntimeError("Unsupported filesystem object: "+rel)
    visit(root)
    if len({x.casefold() for x in result})!=len(result): raise RuntimeError("Case collision")
    return result,directories

def classify(p,size,required,policy):
    parts=p.split("/"); lower=p.lower(); name=parts[-1].lower()
    if p in required: return "git",None,"website-bound original input"
    if name==".env" or (name.startswith(".env.") and name not in (".env.example",".env.template")) or name in ("id_rsa","id_ed25519"):
        return "private_backup",None,"local credential/configuration file; no values published"
    if any(x in (".cache",".envs",".runtime","node_modules","__pycache__",".tooling") for x in parts) or name.endswith((".pyc",".tsbuildinfo")):
        return "recreate",None,"installed environment, runtime, cache or generated bytecode"
    if p.startswith("vendor/CrystalFormer/"):
        if any(x in ("build","crystalformer.egg-info") for x in parts):
            return "recreate",None,"generated duplicate CrystalFormer build/metadata"
        return "git",None,"required pinned original CrystalFormer source or notice"
    if p=="vendor/CrystalFormer-31bb734a.tar.gz":
        return "recreate",None,"pinned upstream source archive; required source is also in Git"
    qe="vendor/quantum_espresso/qe-7.5-win-oneapi-msmpi/"
    if p.startswith(qe) and (p==qe+"README.txt" or p.startswith(qe+"licenses/")):
        return "git",None,"upstream runtime/component licence or distribution notice"
    if p.startswith("vendor/quantum_espresso/"):
        return "recreate",None,"pinned upstream QE runtime/distribution; exact original in Phase1"
    if p=="data/pseudopotentials/SSSP_1.3.0_PBE_efficiency.tar.gz":
        return "recreate",None,"pinned upstream SSSP distribution; used input UPFs archived separately"
    if p.startswith("checkpoints/"):
        return "release","crystalformer-checkpoint","frozen pretrained checkpoint; Phase3 licence review"
    if p.startswith("artifacts/") and "/scratch/" in p:
        return "release","qe-scratch","complete raw scientific scratch/restart evidence"
    if p.startswith("artifacts/") and name.endswith(".joblib"):
        return "release","research-models","frozen fitted-model lineage required for full evidence audits"
    if name.endswith(".upf"):
        return "release","research-inputs","exact pseudopotential input; Phase3 redistribution review"
    if p.startswith("data/mp/") or (p.startswith("data/wbm/") and name.endswith(".gz")):
        return "release","historical-datasets","pinned raw upstream dataset"
    if p in ("data/catalogs/mp_full_compositions.jsonl","data/catalogs/wbm_full_compositions.jsonl"):
        return "release","composition-catalogs","complete frozen catalog indexes"
    if p.startswith(("website/dist/","website/releases/")):
        return "release","website-builds","built production or historical release package"
    if p.startswith("website/deployment/"):
        if name.endswith(".bin") or name==".htaccess":
            return "git",None,"hosting adapter/configuration or required backing sidecar"
        if name.endswith((".md",".mjs",".py",".ps1",".txt",".yml",".yaml",".json",".csv")):
            return "git",None,"deployment source, instructions, inventory or provenance"
        return "release","website-builds","historical compiled deployment payload"
    if size>=policy["max_git_file_bytes"]:
        return "release","other-large-evidence","large frozen file above ordinary Git policy limit"
    return "git",None,"project source, configuration, documentation or small scientific evidence"

def copy_verified(source,target,expected):
    target.parent.mkdir(parents=True,exist_ok=True)
    h=hashlib.sha256(); size=0
    with open(source,"rb") as incoming,open(target,"xb") as outgoing:
        for block in iter(lambda:incoming.read(CHUNK),b""):
            outgoing.write(block); h.update(block); size+=len(block)
    if size!=expected["bytes"] or h.hexdigest()!=expected["sha256"]:
        raise RuntimeError("Copy bytes differ from verified input: "+str(source))
    if sha(target)!=expected["sha256"]: raise RuntimeError("Independent copy verification failed")

def prepare(args):
    source=Path(args.source); phase1=Path(args.phase1_root); out=Path(args.output_root)
    policy=read(args.policy)
    if (source/".git").exists(): raise RuntimeError("Expected pre-import project; root Git already exists")
    for name in ("archives","manifests","git-review-tree","changed-inputs"):
        if (out/name).exists(): raise RuntimeError("Refusing existing prepared output: "+name)
    capture=read(phase1/"project-snapshot/verification.json")
    completion=read(phase1/"PHASE1_COMPLETION.json")
    if capture["status"]!="VERIFIED" or completion["status"]!="COMPLETE": raise RuntimeError("Phase1 not accepted")
    inv=phase1/"project-snapshot/inventory.jsonl"
    if sha(inv)!=completion["original_inventory_sha256"]: raise RuntimeError("Phase1 inventory mismatch")
    known={}
    for line in inv.read_text(encoding="utf-8").splitlines():
        r=json.loads(line)
        if r["kind"]=="file":
            known[r["relative_path"]]={"bytes":r["bytes"],"sha256":r["sha256"],
            "mtime_ns":r["mtime_ns"],"attributes":r["file_attributes"],
            "backup_scope":"phase1-original","backup_relative_path":"project-snapshot/bears/"+r["relative_path"],
            "source_path":str(join(phase1/"project-snapshot/bears",r["relative_path"]))}
    delta=phase1/"phase1-documentation"
    if sha(delta/"inventory.json")!=completion["documentation_inventory_sha256"]: raise RuntimeError("Phase1 delta mismatch")
    for r in read(delta/"inventory.json"):
        known[r["relative_source_path"]]={"bytes":r["bytes"],"sha256":r["sha256"],
        "backup_scope":"phase1-documentation","backup_relative_path":"phase1-documentation/"+r["backup_relative_path"],
        "source_path":str(join(delta,r["backup_relative_path"]))}
    cp="reports/github-publication-phase1/COMPLETION.json"
    known[cp]={"bytes":(phase1/"PHASE1_COMPLETION.json").stat().st_size,
    "sha256":sha(phase1/"PHASE1_COMPLETION.json"),"backup_scope":"phase1-receipt",
    "backup_relative_path":"PHASE1_COMPLETION.json","source_path":str(phase1/"PHASE1_COMPLETION.json")}
    export=read(source/"website/reports/W1_EXPORT.json")
    required=set(export["inputAllowlist"])
    initial,dirs=fast_scan(source,policy)
    emit({"stage":"input-cutoff","files":len(initial),"bytes":sum(x["bytes"] for x in initial.values())})
    (out/"archives").mkdir(parents=True,exist_ok=False)
    (out/"manifests").mkdir(exist_ok=False)
    stage=out/"git-review-tree"; stage.mkdir(exist_ok=False)
    records=[]; paths={}; changed=[]
    for p,m in sorted(initial.items()):
        ref=known.get(p)
        changed_meta=ref is None or m["bytes"]!=ref["bytes"] or ("mtime_ns" in ref and
          (m["mtime_ns"]!=ref["mtime_ns"] or m["attributes"]!=ref["attributes"]))
        if changed_meta or (ref and "mtime_ns" not in ref):
            actual=sha(join(source,p))
            if ref is None or actual!=ref["sha256"]:
                target=join(out/"changed-inputs",p)
                ref={"bytes":m["bytes"],"sha256":actual,"backup_scope":"phase2-current-input",
                "backup_relative_path":"changed-inputs/"+p,"source_path":str(target)}
                copy_verified(join(source,p),target,ref); changed.append(p)
        destination,group,reason=classify(p,m["bytes"],required,policy)
        r={"path":p,"bytes":m["bytes"],"sha256":ref["sha256"],"destination":destination,
        "reason":reason,"backup_scope":ref["backup_scope"],"backup_relative_path":ref["backup_relative_path"]}
        if group:r["archive_group"]=group
        if destination=="release":r["publish_status"]="private-prepared; Phase3 review required"
        records.append(r); paths[p]=Path(ref["source_path"])
        if destination=="git":
            if m["bytes"]>=policy["max_git_file_bytes"]: raise RuntimeError("Git file too large: "+p)
            copy_verified(paths[p],join(stage,p),r)
    bypath={r["path"]:r for r in records}
    if len(bypath)!=len(initial): raise RuntimeError("Incomplete or duplicate disposition")
    if any(p not in bypath or bypath[p]["destination"]!="git" for p in required): raise RuntimeError("Website dependency omitted")
    for p,m in export["inputAllowlist"].items():
        if bypath[p]["sha256"]!=m["sha256"]: raise RuntimeError("Website-bound input changed: "+p)
    cf=[r for r in records if r["destination"]=="git" and r["path"].startswith("vendor/CrystalFormer/")]
    if len(cf)!=86: raise RuntimeError("Pinned CrystalFormer source selection changed")
    must_git=["website/deployment/cache-fix/.htaccess","website/deployment/opaque-repair/.htaccess",
    "website/deployment/latest-link/prepare-publication.mjs","website/deployment/latest-link/test.mjs",
    "website/reports/W6_RESEARCH_VALIDATION.json","website/THIRD_PARTY_NOTICES.md"]
    for p in must_git:
        if bypath[p]["destination"]!="git": raise RuntimeError("Required Git file omitted: "+p)
    host=read(source/"website/reports/W7_HOST_FILES.json")
    active_sidecars=[x for x in host["files"] if x["path"].endswith(".bin")]
    if len(active_sidecars)!=33: raise RuntimeError("Active sidecar inventory changed")
    for item in active_sidecars:
        p="website/"+item["localPath"]
        if bypath[p]["destination"]!="git" or bypath[p]["sha256"]!=item["sha256"]:
            raise RuntimeError("Active sidecar omitted or changed")
    for recipe in policy["pinned_retrieval"]:
        r=bypath[recipe["target"]]
        if r["sha256"]!=recipe["sha256"] or r["bytes"]!=recipe["bytes"]: raise RuntimeError("Pinned recipe differs")
    groups=collections.defaultdict(list)
    for r in records:
        if r["destination"]=="release":
            groups[("project",r["archive_group"])].append((r["path"],r,paths[r["path"]]))
    prodroot=phase1/"production"; prod=read(prodroot/"PRODUCTION_BASELINE.json")
    if sha(prodroot/"PRODUCTION_BASELINE.json")!=completion["production_manifest_sha256"]: raise RuntimeError("Production provenance mismatch")
    production_rows=[]
    for item in prod["files"]:
        p="htdocs/"+item["path"]
        r={"path":p,"bytes":item["expectedBytes"],"sha256":item["expectedSha256"]}
        production_rows.append(r); groups[("production","active-production")].append((p,r,join(prodroot,p)))
    for p in ("PRODUCTION_BASELINE.json","PRODUCTION_BASELINE.sha256","README.md","CAPTURE_PROVENANCE.json",
              "DEPENDENCY_CLOSURE.json","OFFLINE_RESTORE_VERIFICATION.json","tools/verify-production.ps1"):
        f=join(prodroot,p); r={"path":p,"bytes":f.stat().st_size,"sha256":sha(f)}
        production_rows.append(r); groups[("production","active-production")].append((p,r,f))
    archives=[]
    def write_archive(scope,group,number,batch):
        name=f"flamel-{group}-{number:03d}.zip"; target=out/"archives"/name
        members=[]
        with open(target,"xb") as raw,zipfile.ZipFile(raw,"w",compression=zipfile.ZIP_STORED,allowZip64=True) as z:
            for p,r,f in batch:
                safe_name(p); info=zipfile.ZipInfo(p,date_time=(1980,1,1,0,0,0))
                info.create_system=3; info.external_attr=(stat.S_IFREG|0o644)<<16
                h=hashlib.sha256(); count=0
                with open(f,"rb") as inp,z.open(info,"w",force_zip64=True) as dest:
                    for b in iter(lambda:inp.read(CHUNK),b""):
                        dest.write(b); h.update(b); count+=len(b)
                if count!=r["bytes"] or h.hexdigest()!=r["sha256"]: raise RuntimeError("Archive input mismatch: "+p)
                members.append({"archive_path":p,"restore_path":p,"bytes":count,"sha256":h.hexdigest()})
        size=target.stat().st_size
        if size>policy["asset_limit_bytes"]: raise RuntimeError("Archive exceeds policy limit")
        asset={"name":name,"group":group,"bytes":size,"sha256":sha(target),"availability":"local-only",
        "download_url":None,"planned_download_url":"https://github.com/"+policy["repository"]+
        "/releases/download/"+policy["release_tag_planned"]+"/"+name,
        "restore_scope":scope,"members":members}
        archives.append(asset)
        for p,r,f in batch:
            if scope=="project":bypath[p]["archive_name"]=name;bypath[p]["archive_member"]=p
        emit({"stage":"archive-prepared","name":name,"members":len(members),"bytes":size})
    for (scope,group),items in sorted(groups.items()):
        batch=[]; size=0; number=1
        for item in sorted(items,key=lambda x:x[0]):
            need=item[1]["bytes"]+len(item[0].encode("utf-8"))*2+256
            if need>policy["archive_target_bytes"]: raise RuntimeError("Individual member exceeds archive target")
            if batch and size+need>policy["archive_target_bytes"]:
                write_archive(scope,group,number,batch); number+=1; batch=[]; size=0
            batch.append(item); size+=need
        if batch:write_archive(scope,group,number,batch)
    totals=collections.defaultdict(lambda:{"files":0,"bytes":0})
    for r in records:totals[r["destination"]]["files"]+=1;totals[r["destination"]]["bytes"]+=r["bytes"]
    if sum(x["files"] for x in totals.values())!=len(initial):raise RuntimeError("Count accounting mismatch")
    if sum(x["bytes"] for x in totals.values())!=sum(x["bytes"] for x in initial.values()):raise RuntimeError("Byte accounting mismatch")
    if len({r["path"] for r in records if r["destination"]=="release"})!=sum(len(a["members"]) for a in archives if a["restore_scope"]=="project"):
        raise RuntimeError("Release membership accounting mismatch")
    payload="".join(json.dumps(r,sort_keys=True,separators=(",",":"))+"\n" for r in records).encode("utf-8")
    with open(out/"manifests/file-dispositions.jsonl.gz","xb") as raw:
        with gzip.GzipFile(filename="",mode="wb",fileobj=raw,mtime=0,compresslevel=6) as gz:gz.write(payload)
    art={"schema_version":1,"publication_status":policy["publication_status"],"repository":policy["repository"],
    "release_tag_planned":policy["release_tag_planned"],"asset_limit_bytes":policy["asset_limit_bytes"],
    "archives":archives}
    json_new(out/"manifests/artifacts.json",art)
    gitrows=[r for r in records if r["destination"]=="git"]
    json_new(out/"manifests/git-input-files.json",gitrows)
    recreated=[r for r in records if r["destination"]=="recreate"]
    ignored=[]
    for r in gitrows:
        p=r["path"]
        if p.startswith("vendor/"):ignored.append({"path":p,"rule":"vendor/"})
        elif p.endswith(".pkl"):ignored.append({"path":p,"rule":"*.pkl"})
        elif p.startswith("website/") and p.endswith(".log"):ignored.append({"path":p,"rule":"website/*.log"})
    summary={"schema_version":1,"tool_version":VERSION,"prepared_utc":dt.datetime.now(dt.timezone.utc).isoformat(),
    "status":"PREPARED_NOT_YET_ACCEPTED","input_files":len(initial),"input_bytes":sum(x["bytes"] for x in initial.values()),
    "directories_including_root":len(dirs),"categories":dict(totals),"required_website_inputs":len(required),
    "crystalformer_git_source_files":len(cf),"qe_git_notices":sum(r["destination"]=="git" and r["path"].startswith("vendor/quantum_espresso/") for r in records),
    "git_input_files":len(gitrows),"git_input_bytes":sum(r["bytes"] for r in gitrows),
    "largest_git_file_bytes":max(r["bytes"] for r in gitrows),
    "all_git_input_files_verified_in_review_tree":True,"active_image_sidecars_in_git":33,
    "all_deployment_bin_files_in_git":sum(r["destination"]=="git" and r["path"].startswith("website/deployment/") and r["path"].endswith(".bin") for r in records),
    "release_archive_count":len(archives),"release_archive_bytes":sum(a["bytes"] for a in archives),
    "project_release_members":sum(len(a["members"]) for a in archives if a["restore_scope"]=="project"),
    "production_release_members":sum(len(a["members"]) for a in archives if a["restore_scope"]=="production"),
    "existing_ignore_conflicts":ignored,"changed_or_new_since_phase1":changed,
    "file_dispositions_sha256":sha(out/"manifests/file-dispositions.jsonl.gz"),
    "artifacts_manifest_sha256":sha(out/"manifests/artifacts.json"),
    "git_inputs_manifest_sha256":sha(out/"manifests/git-input-files.json"),
    "phase1_inventory_sha256":completion["original_inventory_sha256"],
    "phase1_backup_root":str(phase1),"local_archives":str(out/"archives"),
    "local_git_review_tree":str(stage),"publication_uploaded":False,"phase3_security_licence_clearance":False,
    "control_output_paths":policy["phase2_control_paths"],
    "cutoff_scope":"All input files except declared Phase2 generated-control paths. Those controls are separately sealed in the final external receipt."}
    json_new(out/"manifests/summary.json",summary)
    final,finaldirs=fast_scan(source,policy)
    if final!=initial or finaldirs!=dirs:raise RuntimeError("Source metadata/path set changed during preparation")
    json_new(out/"manifests/preparation-verification.json",{"status":"PASSED","all_input_paths_classified_once":True,
    "counts_and_bytes_reconcile":True,"source_metadata_unchanged":True,"no_git_init":True,"no_upload":True})
    emit(summary)

